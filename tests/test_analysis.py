def _mutations():
    def four_queries(p): p["target_search_queries"].pop()
    def six_queries(p): p["target_search_queries"].append(copy.deepcopy(p["target_search_queries"][0]))
    def four_services(p): p["top_services"].pop()
    def bad_platform(p): p["target_search_queries"][0]["platforms"] = ["tiktok"]
    def no_platform(p): p["target_search_queries"][0]["platforms"] = []
    def bad_origin(p): p["top_services"][0]["origin"] = "guessed"
    def bad_evidence(p): p["competitor_analysis"]["competitors"][0]["evidence_type"] = "trust_me"
    def missing_audience(p): del p["target_audience"]["primary_audience"]
    def missing_brand_name(p): del p["brand"]["name"]
    def too_few_keywords(p): p["seo_improvements"]["keyword_recommendations"]["secondary_keywords"] = ["one"]
    return [four_queries, six_queries, four_services, bad_platform, no_platform, bad_origin, bad_evidence,
            missing_audience, missing_brand_name, too_few_keywords]


@pytest.mark.parametrize("mutate", _mutations(), ids=lambda f: f.__name__)
def test_llm_output_that_violates_the_schema_is_rejected(mutate):
    payload = make_llm_payload()
    mutate(payload)
    with pytest.raises(ValidationError):
        LLMAnalysis.model_validate(payload)


def test_a_valid_payload_passes_the_schema():
    assert LLMAnalysis.model_validate(make_llm_payload()).brand.name == "Acme Cloud"


