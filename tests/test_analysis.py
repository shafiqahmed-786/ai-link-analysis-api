async def test_repeat_requests_are_served_from_cache_without_new_fetches_or_llm_calls():
    extractor, llm = FakeExtractor(), FakeLLM()
    service = make_service(extractor=extractor, llm=llm, cache=TTLCache(60))
    first = await service.analyze(URL)
    second = await service.analyze("https://EXAMPLE.com")  # normalizes to the same key
    assert first.metadata.cached is False and second.metadata.cached is True
    assert extractor.calls == 1 and len(llm.calls) == 1


async def test_failed_analyses_are_not_cached():
    extractor = FakeExtractor(error=WebsiteInaccessibleError())
    service = make_service(extractor=extractor, cache=TTLCache(60))
    for _ in range(2):
        with pytest.raises(WebsiteInaccessibleError):
            await service.analyze(URL)
    assert extractor.calls == 2


async def test_unconfigured_llm_fails_fast_before_the_website_is_fetched():
    extractor = FakeExtractor()
    with pytest.raises(LLMNotConfiguredError):
        await make_service(llm=FakeLLM(configured=False), extractor=extractor).analyze(URL)
    assert extractor.calls == 0


@pytest.mark.parametrize("url, error", [("not a url", InvalidURLError), ("http://localhost", UnsafeURLError),
                                        ("http://169.254.169.254/", UnsafeURLError), ("ftp://example.com", UnsafeURLError)])
async def test_bad_urls_are_rejected_before_any_work(url, error):
    extractor, llm = FakeExtractor(), FakeLLM()
    with pytest.raises(error):
        await make_service(extractor=extractor, llm=llm).analyze(url)
    assert extractor.calls == 0 and llm.calls == []


