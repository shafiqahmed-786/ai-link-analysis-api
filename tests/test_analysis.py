async def test_response_contains_the_five_required_sections_and_round_trips_through_the_schema():
    response = await make_service().analyze(URL)
    dumped = response.model_dump(mode="json")

    assert response.success is True and response.website == URL
    assert set(dumped) == {"success", "website", "brand", "analysis", "metadata"}
    assert set(dumped["analysis"]) == {
        "competitor_analysis", "target_search_queries", "seo_improvements", "top_services", "target_audience",
    }
    assert AnalysisResponse.model_validate(dumped).model_dump(mode="json") == dumped


